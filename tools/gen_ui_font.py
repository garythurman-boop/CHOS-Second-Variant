#!/usr/bin/env python3
"""Generate CHOS's compact 4-bit antialiased DejaVu Sans UI bitmap fonts.

Requires Pillow and licensed DejaVu Sans regular/bold TTFs installed locally.
The TTF files are never copied into the CHOS source tree; only raster glyphs
are embedded, alongside docs/DEJAVU_FONT_LICENSE.txt.
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FIRST = 32
COUNT = 95
HEIGHT = 14
WIDTH = 14
ROW_BYTES = WIDTH // 2
BASELINE = 10


def glyph_data(font_path: str):
    font = ImageFont.truetype(font_path, 12)
    advances = []
    glyphs = []
    for code in range(FIRST, FIRST + COUNT):
        ch = chr(code)
        advance = max(2, min(WIDTH, math.ceil(font.getlength(ch)) + 1))
        advances.append(advance)
        image = Image.new("L", (WIDTH, HEIGHT), 0)
        ImageDraw.Draw(image).text((0, BASELINE), ch, fill=255, font=font, anchor="ls")
        packed_rows = []
        for y in range(HEIGHT):
            packed = []
            for x in range(0, WIDTH, 2):
                p0 = (image.getpixel((x, y)) * 15 + 127) // 255
                p1 = (image.getpixel((x + 1, y)) * 15 + 127) // 255
                packed.append((p0 << 4) | p1)
            packed_rows.append(packed)
        glyphs.append(packed_rows)
    if max(advances) > WIDTH:
        raise RuntimeError("font glyph advance exceeds embedded cell width")
    return advances, glyphs


def emit_font(name: str, advances: list[int], glyphs: list[list[list[int]]]) -> str:
    out = [f"static const uint8_t {name}_advance[CHOS_UI_GLYPH_COUNT] = {{"]
    for i in range(0, len(advances), 19):
        out.append("    " + ", ".join(str(v) for v in advances[i:i + 19]) + ",")
    out.append("};")
    out.append(f"static const uint8_t {name}_bitmap[CHOS_UI_GLYPH_COUNT][CHOS_UI_FONT_HEIGHT][CHOS_UI_FONT_ROW_BYTES] = {{")
    for glyph in glyphs:
        out.append("    {")
        for row in glyph:
            out.append("        {" + ", ".join(f"0x{v:02x}u" for v in row) + "},")
        out.append("    },")
    out.append("};")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--regular", default="/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    parser.add_argument("--bold", default="/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
    parser.add_argument("--output", default="kernel/gfx/font_ui_dejavu.h")
    args = parser.parse_args()
    regular_adv, regular = glyph_data(args.regular)
    bold_adv, bold = glyph_data(args.bold)
    header = '''/* Generated by tools/gen_ui_font.py from licensed DejaVu Sans fonts. */
#ifndef CHOS_FONT_UI_DEJAVU_H
#define CHOS_FONT_UI_DEJAVU_H
#include <stdint.h>
#define CHOS_UI_GLYPH_FIRST 32u
#define CHOS_UI_GLYPH_COUNT 95u
#define CHOS_UI_FONT_WIDTH 14u
#define CHOS_UI_FONT_HEIGHT 14u
#define CHOS_UI_FONT_ROW_BYTES 7u
#define CHOS_UI_FONT_BASELINE 10u
'''
    header += emit_font("chos_ui_regular", regular_adv, regular) + "\n\n"
    header += emit_font("chos_ui_bold", bold_adv, bold) + "\n"
    header += "\n#endif /* CHOS_FONT_UI_DEJAVU_H */\n"
    Path(args.output).write_text(header)
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
