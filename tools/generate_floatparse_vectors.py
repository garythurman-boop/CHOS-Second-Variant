#!/usr/bin/env python3
"""Floating text fixtures from exact decimal/hex ratios; host libc is a secondary oracle."""
import argparse,ctypes,random,struct,re,json
from fractions import Fraction
from pathlib import Path
from generate_quad_vectors import pack,pair

def ratio(text):
    if 'x' not in text.lower():return Fraction(text)
    m=re.fullmatch(r'([+-]?)0[xX]([0-9a-fA-F]*)(?:\.([0-9a-fA-F]*))?[pP]([+-]?\d+)',text);assert m,text
    sign,whole,part,exponent=m.groups();part=part or ''
    n=Fraction(int((whole+part) or '0',16),16**len(part))*Fraction(2)**int(exponent)
    return -n if sign=='-' else n

def exact_decimal(n):
    sign='-' if n<0 else '';n=abs(n);k=n.denominator.bit_length()-1;assert n.denominator==1<<k
    digits=str(n.numerator*5**k).rjust(k+1,'0')
    return sign+(digits[:-k]+'.'+digits[-k:] if k else digits)

def generate():
    rng=random.Random(0x464c4f4154534341);lib=ctypes.CDLL(None,use_errno=True)
    for name,kind in [('strtod',ctypes.c_double),('strtof',ctypes.c_float)]:
        f=getattr(lib,name);f.argtypes=[ctypes.c_char_p,ctypes.POINTER(ctypes.c_void_p)];f.restype=kind
    numbers=['0','-0','-0.00','1','-1','0.1','-0.5','1e-6000','-1e6000','1.7976931348623157e308','2.2250738585072014e-308','4.9406564584124654e-324','3.4028234663852886e38','1.1754943508222875e-38','1.401298464324817e-45','0x1.fffffffffffffp1023','0x1p-1074','0x1p-149','0x1p-16494','0x1.ffffffffffffffffffffffffffffp16383','0x0.ffffffffffffffffffffffffffffp-16382','0x1p16384']
    numbers += [exact_decimal(Fraction(1)+Fraction(1,1<<n)) for n in [24,53,113]]
    for _ in range(96):numbers.append(('-' if rng.getrandbits(1) else '')+str(rng.randrange(10**10))+'.'+str(rng.randrange(10**20)).rjust(20,'0')+'e'+str(rng.randint(-6000,6000)))
    for _ in range(48):numbers.append(('-' if rng.getrandbits(1) else '')+'0x'+format(rng.getrandbits(32),'x')+'.'+format(rng.getrandbits(116),'029x')+'p'+str(rng.randint(-17000,17000)))
    out='/* Generated by tools/generate_floatparse_vectors.py; exact ratio oracle. */\n#ifndef CHOS_FLOATPARSE_VECTORS_H\n#define CHOS_FLOATPARSE_VECTORS_H\n#include "quad_vectors.h"\n'
    out+='typedef struct {const char *text;unsigned end;quad_bits_t wide;uint64_t d;uint32_t f;int de,fe;} floatparse_vector_t;\nstatic const floatparse_vector_t floatparse_vectors[]={\n'
    for i,number in enumerate(numbers):
        leading=' \t' if i%3==0 else '';text=leading+number+'tail';n=ratio(number);bits=[]
        for p,e in [(113,15),(53,11),(24,8)]:
            b=pack(n,p,e)
            if not n and number.startswith('-'):b|=1<<(p+e-1)
            bits.append(b)
        errors=[]
        for name,width in [('strtod',64),('strtof',32)]:
            memory=ctypes.create_string_buffer(text.encode());end=ctypes.c_void_p();ctypes.set_errno(0)
            v=getattr(lib,name)(memory,ctypes.byref(end));errors.append(ctypes.get_errno())
            observed=int.from_bytes(struct.pack('>d' if width==64 else '>f',v),'big')
            assert observed==bits[1 if width==64 else 2],(text,width,hex(observed),hex(bits[1 if width==64 else 2]))
            assert end.value-ctypes.addressof(memory)==len(leading+number)
        out+=' {'+json.dumps(text)+','+str(len(leading+number))+','+pair(bits[0])+',UINT64_C(0x%016x),UINT32_C(0x%08x),%d,%d},\n'%(bits[1],bits[2],errors[0],errors[1])
    out+='};\n'
    for name,power in [('FLOAT',24),('DOUBLE',53),('WIDE',113)]:out+='#define FLOATPARSE_'+name+'_HALFWAY '+json.dumps(exact_decimal(Fraction(1)+Fraction(1,1<<power)))+'\n'
    return out+'#endif\n'
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,default=Path('tests/floatparse_vectors.h'));p.add_argument('--check',action='store_true');o=p.parse_args();s=generate()
    if o.check:assert o.out.read_text()==s,'float parse vectors changed'
    else:o.out.write_text(s)
    print('Exact-ratio floating parsing fixtures verified' if o.check else 'Wrote '+str(o.out))
