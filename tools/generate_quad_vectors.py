#!/usr/bin/env python3
"""Reproducible IEEE binary128 regression vectors from exact rational arithmetic.

This independent reference rounds integer ratios to nearest/ties-to-even. It
never uses the compiler-rt implementation or host long double as its oracle.
"""
import argparse,random,struct
from fractions import Fraction
from pathlib import Path

def unpack(bits,precision=113,exponent_bits=15):
    frac=precision-1;bias=(1<<(exponent_bits-1))-1
    sign=bits>>(frac+exponent_bits);exp=(bits>>frac)&((1<<exponent_bits)-1)
    mant=bits&((1<<frac)-1)
    assert exp!=(1<<exponent_bits)-1
    if exp:mant|=1<<frac
    power=(exp-bias if exp else 1-bias)-frac
    value=Fraction(mant<<power) if power>=0 else Fraction(mant,1<<-power)
    return -value if sign else value

def pack(value,precision=113,exponent_bits=15):
    frac=precision-1;bias=(1<<(exponent_bits-1))-1
    sign=int(value<0);value=abs(value)
    if not value:return 0
    n,d=value.numerator,value.denominator
    exponent=n.bit_length()-d.bit_length()
    if (n < d<<exponent) if exponent>=0 else (n<<-exponent < d):exponent-=1
    power=frac-max(exponent,1-bias)
    if power>=0:n<<=power
    else:d<<=-power
    q,remainder=divmod(n,d)
    if 2*remainder>d or (2*remainder==d and q&1):q+=1
    if q==1<<precision:q>>=1;exponent+=1
    if exponent>bias:return (sign<<(frac+exponent_bits))|(((1<<exponent_bits)-1)<<frac)
    encoded_exp=0 if q<1<<frac else max(exponent,1-bias)+bias
    return (sign<<(frac+exponent_bits))|(encoded_exp<<frac)|(q&((1<<frac)-1))

def pair(n):return '{UINT64_C(0x%016x),UINT64_C(0x%016x)}'%(n&((1<<64)-1),n>>64)
def line(values):return ' {'+','.join(pair(n) for n in values)+'},\n'
def generate():
    rng=random.Random(0x43484f5351554144)
    # Check our ratio rounding against the host binary64 implementation as a
    # secondary oracle, including halfway/normal/subnormal/overflow boundaries.
    for _ in range(3000):
        n=rng.getrandbits(180);d=rng.getrandbits(160)+1
        value=Fraction(n,d)*Fraction(2)**rng.randint(-1100,1000)
        if rng.getrandbits(1):value=-value
        try:observed=int.from_bytes(struct.pack('>d',float(value)),'big')
        except OverflowError:observed=(int(value<0)<<63)|0x7ff0000000000000
        assert pack(value,53,11)==observed
    edge=[1,2,(1<<112)-1,1<<112,(1<<112)+1,(16383<<112),(16383<<112)+1,((32766<<112)|((1<<112)-1)),(16382<<112)]
    inputs=[]
    for i,a in enumerate(edge):
        for b in edge[:7]:
            inputs.append((a|((i&1)<<127),b))
    for _ in range(129):
        def random_bits():return (rng.getrandbits(1)<<127)|(rng.randint(1,32766)<<112)|rng.getrandbits(112)
        inputs.append((random_bits(),random_bits()))
    text='/* Generated by tools/generate_quad_vectors.py; exact rational oracle. */\n#ifndef CHOS_QUAD_VECTORS_H\n#define CHOS_QUAD_VECTORS_H\n#include <stdint.h>\ntypedef struct {uint64_t lo,hi;} quad_bits_t;\n'
    text+='typedef struct {quad_bits_t a,b,sum,difference,product,quotient,narrow64,narrow32;} quad_vector_t;\nstatic const quad_vector_t quad_vectors[]={\n'
    for a,b in inputs:
        x,y=unpack(a),unpack(b)
        text+=line([a,b,pack(x+y),pack(x-y),pack(x*y),pack(x/y),pack(x,53,11),pack(x,24,8)])
    text+='};\ntypedef struct {quad_bits_t integer,wide;unsigned is_signed;} quad_integer_t;\nstatic const quad_integer_t quad_integers[]={\n'
    for signed in [0,1]:
        for width in [1,16,31,32,63,64,100,112,113,126,127]:
            for offset in [-1,0,1]:
                n=(1<<width)+offset
                if signed and width==127 and offset>=0:continue
                if signed and rng.getrandbits(1):n=-n
                text+=' {'+pair(n&((1<<128)-1))+','+pair(pack(Fraction(n)))+','+str(signed)+'},\n'
    text+='};\ntypedef struct {uint64_t narrow;quad_bits_t wide;unsigned width;} quad_extend_t;\nstatic const quad_extend_t quad_extends[]={\n'
    for precision,expbits in [(24,8),(53,11)]:
        frac=precision-1;width=precision+expbits
        for _ in range(64):
            n=(rng.getrandbits(1)<<(width-1))|(rng.randrange((1<<expbits)-1)<<frac)|rng.getrandbits(frac)
            text+=' {UINT64_C(0x%016x),'%n+pair(pack(unpack(n,precision,expbits)))+','+str(width)+'},\n'
    text+='};\n#endif\n'
    return text
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,default=Path('tests/quad_vectors.h'));p.add_argument('--check',action='store_true');o=p.parse_args();text=generate()
    if o.check:assert o.out.read_text()==text,'quad vectors changed; regenerate and review'
    else:o.out.write_text(text)
    print('Exact-rational binary128 vectors verified' if o.check else 'Wrote '+str(o.out))
