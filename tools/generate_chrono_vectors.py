#!/usr/bin/env python3
"""Independent Python datetime/calendar vectors for original native libc++ chrono."""
import argparse,datetime,calendar,random,pathlib
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');o=p.parse_args()
epoch=datetime.date(1970,1,1);dates={datetime.date(y,m,d) for y in [1,4,100,400,1600,1700,1900,1969,1970,2000,2100,2400,9999] for m,d in [(1,1),(2,28),(3,1),(12,31)]}
for y in [4,400,1600,2000,2400]:dates.add(datetime.date(y,2,29))
r=random.Random(0x4348524f4e4f)
while len(dates)<512:dates.add(datetime.date.fromordinal(r.randrange(1,datetime.date.max.toordinal()+1)))
rows=[]
for d in sorted(dates):rows.append(' {%d,%d,%d,%d,%d,%d,%d},'%((d-epoch).days,d.year,d.month,d.day,(d.weekday()+1)%7,d.timetuple().tm_yday,calendar.monthrange(d.year,d.month)[1]))
text='// Generated by tools/generate_chrono_vectors.py; independent Python date/calendar.\nstruct CalendarVector {int days,year,month,day,weekday,yearday,monthdays;};\nstatic constexpr CalendarVector calendar_vectors[]={\n'+'\n'.join(rows)+'\n};\n'
f=pathlib.Path(__file__).resolve().parents[1]/'tests/native_chrono/calendar_vectors.h'
if o.check:assert f.read_text()==text,'calendar vectors changed; regenerate explicitly'
else:f.write_text(text)
print('Independent chrono vectors:',len(rows),'Python datetime years1..9999')
