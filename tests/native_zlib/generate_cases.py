#!/usr/bin/env python3
"""Generate fixed independent host-libz streams and exact original payloads.

The host Python extension is not linked into either tested executable. Preserve
its runtime version and complete stream/payload hashes to describe this oracle.
"""
import argparse
import hashlib
import json
import pathlib
import zlib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out', type=pathlib.Path, required=True)
args = parser.parse_args()
args.out.mkdir(parents=True, exist_ok=True)
state = 0x13579BDF
mixed = bytearray()
for i in range(49152):
    state ^= (state << 13) & 0xFFFFFFFF
    state ^= state >> 17
    state ^= (state << 5) & 0xFFFFFFFF
    state &= 0xFFFFFFFF
    mixed.append((state & 255) if i % 8192 < 2048 else (i * 7 + i // 97) & 31)
payloads = [b'', b'CHOS memory compression streams\x00\xff\n' * 19, bytes(mixed)]
names = ['empty', 'binary-text', 'window-crossing']
manifest = {'oracle': 'Python standard-library zlib extension (host only)',
            'runtime_version': zlib.ZLIB_RUNTIME_VERSION,
            'compile_version': zlib.ZLIB_VERSION, 'cases': []}
lines = ['/* Generated by tests/native_zlib/generate_cases.py; do not edit. */',
         '#ifndef CHOS_ZLIB_CASES_H', '#define CHOS_ZLIB_CASES_H',
         'struct ZlibCase { const char *name; const unsigned char *plain; size_t plain_length;',
         ' const unsigned char *encoded; size_t encoded_length; int window_bits; };']
def array(name, data):
    # C does not permit an empty array; its explicit logical length remains0.
    lines.append('static const unsigned char ' + name + '[] = {')
    for offset in range(0, len(data), 24):
        lines.append(','.join(str(value) for value in data[offset:offset+24]) + ',')
    if not data:
        lines.append('0')
    lines.append('};')
for index, plain in enumerate(payloads):
    array(f'plain_{index}', plain)
rows = []
for index, plain in enumerate(payloads):
    for label, bits in [('raw', -15), ('zlib', 15), ('gzip', 31)]:
        compressor = zlib.compressobj(6, zlib.DEFLATED, bits)
        encoded = compressor.compress(plain) + compressor.flush(zlib.Z_FINISH)
        identifier = f'encoded_{index}_{label}'
        array(identifier, encoded)
        case_name = names[index] + '-' + label
        rows.append(' {"%s", plain_%d, %d, %s, %d, %d},' %
                    (case_name, index, len(plain), identifier, len(encoded), bits))
        manifest['cases'].append({'name': case_name, 'plain_length': len(plain),
            'encoded_length': len(encoded), 'window_bits': bits,
            'plain_sha256': hashlib.sha256(plain).hexdigest(),
            'encoded_sha256': hashlib.sha256(encoded).hexdigest()})
lines.extend(['static const struct ZlibCase zlib_cases[] = {', *rows,
              '};', '#define ZLIB_CASE_COUNT (sizeof(zlib_cases)/sizeof(*zlib_cases))', '#endif', ''])
header = '\n'.join(lines)
(args.out / 'zlib-cases.h').write_text(header)
manifest['header_sha256'] = hashlib.sha256(header.encode()).hexdigest()
(args.out / 'cases.json').write_text(json.dumps(manifest, indent=2) + '\n')
