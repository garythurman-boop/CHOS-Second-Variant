#!/usr/bin/env python3
"""Regenerate committed scalar math fixtures with mpmath at400 decimal digits.
This is a numerical regression fixture, not an exhaustive C/ECMAScript suite.
"""
import argparse,pathlib,struct,mpmath as mp
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');o=p.parse_args()
mp.mp.dps=400
positive=[0.0,2.**-1074,2.**-149,2.**-126,float.fromhex("0x1.fffffep+127"),1e-300,1e-100,1e-20,1e-8,.1,.25,.5,1.,2.,10.,100.,1e20,1e100,1e300]
signed=[-100.,-10.,-2.,-1.,-.5,-.1,-1e-9,0.,1e-9,.1,.5,1.,2.,10.,100.]
unit=[-.999,-.9,-.5,-.1,0.,.1,.5,.9,.999]
functions=[('sqrt',mp.sqrt,positive),('sin',mp.sin,signed+[1e20,1e100,1e300]),('cos',mp.cos,signed+[1e20,1e100,1e300]),('tan',mp.tan,signed),('exp',mp.exp,[-740.,-700.,-20.,-1.,0.,1.,20.,88.,709.]),('exp2',lambda x:mp.power(2,x),[-1074.,-1022.,-149.,-126.,-10.,-.5,0.,.5,10.,100.,1023.]),('log',mp.log,positive[1:]),('log2',lambda x:mp.log(x,2),positive[1:]),('log10',mp.log10,positive[1:]),('log1p',mp.log1p,unit+[1.,10.,1e100]),('expm1',mp.expm1,signed+[-700.,709.]),('atan',mp.atan,signed+[1e100]),('asin',mp.asin,unit),('acos',mp.acos,unit),('atan2',mp.atan2,signed),('pow',mp.power,[.1,.5,1.,2.,10.]),('hypot',lambda x,y:mp.sqrt(x*x+y*y),positive),('cbrt',lambda x:-mp.root(-x,3) if x<0 else mp.root(x,3),signed),('erf',mp.erf,signed),('erfc',mp.erfc,[-10.,-2.,-1.,-.1,0.,.1,1.,2.,10.]),('tgamma',mp.gamma,[-4.5,-1.5,-.5,.1,.5,1.,2.,5.,10.,30.]),('lgamma',lambda x:mp.log(abs(mp.gamma(x))),[-4.5,-1.5,-.5,.1,.5,1.,2.,5.,10.,100.]),('asinh',mp.asinh,signed),('acosh',mp.acosh,[1.,1.00001,1.5,2.,10.,1e100]),('atanh',mp.atanh,unit),('sinh',mp.sinh,signed),('cosh',mp.cosh,signed),('tanh',mp.tanh,signed)]
def f32(x):
 try:return struct.unpack('<f',struct.pack('<f',float(x)))[0]
 except OverflowError:return float('-inf') if x<0 else float('inf')
def bits(x,width):return int.from_bytes(struct.pack('<f' if width==32 else '<d',x),'little')
rows=[]
for op,(name,fn,values) in enumerate(functions):
 for width in [64,32]:
  for value in values:
   x=f32(value) if width==32 else value
   if not mp.isfinite(x):continue
   if width==32 and x==0 and value!=0 and name in ['log','log2','log10']:continue
   ys=[-2.,-.5,.5,2.,3.] if name=='pow' else [0.1,1.,-2.] if name=='atan2' else [.1,1e-100,1e100] if name=='hypot' else [0.]
   for y in ys:
    y=f32(y) if width==32 else y
    if not mp.isfinite(y):continue
    a,b=mp.mpf(x),mp.mpf(y)
    result=fn(a,b) if name in ['pow','atan2','hypot'] else fn(a)
    if not isinstance(result,mp.mpf):raise ValueError((name,x,y,result))
    rounded=f32(result) if width==32 else float(result)
    rows.append((bits(x,width),bits(y,width),bits(rounded,width),op,width,0 if name=='sqrt' else 4))
text='/* Generated by tests/generate_libm_vectors.py; mpmath '+mp.__version__+',400 decimal digits. */\n'
text+='typedef struct {uint64_t a,b,expected;unsigned op,width,ulp;} math_vector_t;\n'
text+='static const math_vector_t math_vectors[]={\n'+''.join('{UINT64_C(0x%x),UINT64_C(0x%x),UINT64_C(0x%x),%u,%u,%u},\n'%r for r in rows)+'};\n'
target=pathlib.Path(__file__).with_name('libm_vectors.h')
if o.check:assert target.read_text()==text,'math fixtures changed'
else:target.write_text(text)
print(len(rows),'MP-backed scalar fixtures; mpmath',mp.__version__)
