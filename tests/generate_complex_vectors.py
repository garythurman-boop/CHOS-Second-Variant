#!/usr/bin/env python3
"""Complex arithmetic regression oracle using mpmath200 decimal digits."""
import argparse,struct,pathlib,mpmath as mp
mp.mp.dps=200
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');o=p.parse_args()
def rounded(x,width):return struct.unpack('<f' if width==32 else '<d',struct.pack('<f' if width==32 else '<d',float(x)))[0]
def bits(x,width):return int.from_bytes(struct.pack('<f' if width==32 else '<d',x),'little')
rows=[]
for width in [32,64]:
 for x in [-3.,-.5,.1,.5,1.,2.]:
  for y in [-.75,.25,2.]:
   x,y=rounded(x,width),rounded(y,width);z=mp.mpc(mp.mpf(x),mp.mpf(y));w=mp.mpc(mp.mpf(rounded(.75,width)),mp.mpf(rounded(-.25,width)))
   for op,result in enumerate([z*w,z/w,mp.sqrt(z),mp.exp(z),mp.log(z),mp.sin(z),mp.cos(z),mp.tan(z),mp.mpc(abs(z),0),mp.mpc(mp.arg(z),0),mp.power(z,w)]):
    rows.append((bits(x,width),bits(y,width),bits(.75,width),bits(-.25,width),bits(rounded(result.real,width),width),bits(rounded(result.imag,width),width),op,width,8))
s='/* Generated by tests/generate_complex_vectors.py; mpmath '+mp.__version__+',200 decimal digits. */\n'
s+='typedef struct {uint64_t ar,ai,br,bi,re,im;unsigned op,width,error_eps;} complex_vector_t;\nstatic const complex_vector_t complex_vectors[]={\n'
s+=''.join('{UINT64_C(0x%x),UINT64_C(0x%x),UINT64_C(0x%x),UINT64_C(0x%x),UINT64_C(0x%x),UINT64_C(0x%x),%u,%u,%u},\n'%row for row in rows)+'};\n'
target=pathlib.Path(__file__).with_name('complex_vectors.h')
if o.check:assert target.read_text()==s,'complex vectors changed'
else:target.write_text(s)
print(len(rows),'MP-backed complex fixtures; mpmath',mp.__version__)
